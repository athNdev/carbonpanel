//go:build unix

package docker

import (
	"os"
	"syscall"
)

// dataOwnerUID reports the uid that owns path when the platform exposes it.
func dataOwnerUID(path string) (int, bool) {
	info, err := os.Stat(path)
	if err != nil {
		return 0, false
	}
	stat, ok := info.Sys().(*syscall.Stat_t)
	if !ok {
		return 0, false
	}
	return int(stat.Uid), true
}
