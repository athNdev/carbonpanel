"""Isolated build/publish boundary for verified managed-node runtime artifacts.

This module is deliberately independent of ``scripts/release.py``. It owns a
separate immutable version domain (``runtime-vMAJOR.MINOR.PATCH``, reserved by
ADR 0033) and can never publish a Carbon Panel application release or a module
image. Every write is gated by :func:`publication_gate`, which requires all of:

  * an explicit operator ``workflow_dispatch`` (no automatic event can write),
  * the trusted default-branch ref,
  * ``publish=true`` opt-in,
  * a valid, independent runtime version (never a ``v*``/``mod-*`` app ref),
  * an artifact kind that has real clean import/boot evidence in a sibling lane
    (QCOW2 VM, unprivileged LXC rootfs or portable installer),
  * a full 40-hex source SHA whose exact commit is an ancestor of main and has
    green push CI (``verify_main_ci``; never a checkbox),
  * an identity assertion bound to that exact version, commit, artifact and
    project owner.

Home-hypervisor disk formats (VHDX/VDI/VMDK/OVA/OVF/bhyve) are intentionally
NOT in the publishable set: primary-source research found no real clean
import/boot evidence for them in this implementation lane, so the portable
guest installer is the supported path. See docs/node-runtime/.

No network write, registry push, GitHub release or host provisioning happens in
this module. It only computes decisions and integrity records.
"""

from __future__ import annotations

import argparse
import hashlib
import json
import os
import re
import subprocess
import sys
import uuid
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent

# --- Independent version / ownership domains --------------------------------

RUNTIME_VERSION = re.compile(
    r"runtime-v(0|[1-9][0-9]*)\.(0|[1-9][0-9]*)\.(0|[1-9][0-9]*)")
FULL_SHA = re.compile(r"[0-9a-f]{40}")
TRUSTED_REF = "refs/heads/main"
DEFAULT_REPOSITORY = "athNdev/carbonpanel"

# Publishable kinds. These map to thin, allowlisted wrapper scripts that
# delegate to the REAL entry points owned by the QCOW2/LXC/installer artifact
# lanes; this lane publishes their outputs under one independent version and
# does not reimplement their build logic. The wrappers exist because the
# real entry points have heterogeneous interfaces (a Python module, a bash
# ``build`` subcommand and a host-mutating systemd qualification fixture)
# while this workflow invokes one uniform ``bash <script> --version --commit
# --output`` contract. Both the wrapper and its delegate MUST exist on disk or
# the build step fails closed (see ``preflight_build``). No wrapper resolves to
# a script outside these explicit maps.
VERIFIED_ARTIFACTS = ("qcow2", "lxc-rootfs", "installer")
BUILD_SCRIPTS = {
    "qcow2": "scripts/build-runtime-qcow2.sh",
    "lxc-rootfs": "scripts/build-runtime-lxc.sh",
    "installer": "scripts/build-runtime-installer.sh",
}
# The real, checked-in entry points on main that each wrapper delegates to.
# ADR 0035/0036 and knowledge/architecture/node-installer.md own these lanes.
BUILD_DELEGATES = {
    "qcow2": "scripts/node_vm_build.py",
    "lxc-rootfs": "packaging/node-lxc/build-rootfs.sh",
    "installer": "scripts/qualify-node-installer-systemd.sh",
}
# Documented but UNSUPPORTED until real clean import/boot evidence exists.
UNSUPPORTED_FORMATS = ("vhdx", "vdi", "vmdk", "ova", "ovf", "bhyve", "vhd")
RESERVED_PRERELEASE = frozenset(
    {"verify", "verification", "test", "testing", "dryrun", "dry-run", "docs"})

IDENTITY_HEADER = "runtime-artifact-identity-v1"
IDENTITY_FIELDS = frozenset(
    {"version", "commit", "artifact", "owner", "publisher", "statement"})

# Files generated by the integrity/signing steps rather than by the artifact
# build. They are never checksummed or inventoried as build artifacts, but they
# MUST be allowed to coexist with the staged artifact during bundle verification
# (cosign writes signature.sig/.bundle before verify-bundle runs).
INTEGRITY_RECORDS = frozenset({
    "SHA256SUMS", "sbom.cdx.json", "signature.json",
    "signature.sig", "signature.bundle",
})
WORKFLOW_PATH = ".github/workflows/runtime-artifacts.yml"
OIDC_ISSUER = "https://token.actions.githubusercontent.com"


def project_owner(repository=None):
    """Existing project ownership is derived from the GitHub repository name.

    Never a credential or a machine-specific path. ``athNdev/carbonpanel``
    owns the artifacts; this only normalises the namespace for the assertion.
    """
    repo = (repository or os.environ.get("GITHUB_REPOSITORY", DEFAULT_REPOSITORY))
    owner = repo.split("/", 1)[0].lower()
    if not owner or owner != re.sub(r"[^a-z0-9-]", "", owner):
        raise ValueError("Invalid project owner in GITHUB_REPOSITORY")
    return owner


def valid_runtime_version(value):
    """True only for an immutable independent runtime version.

    Refuses panel ``v*``, module ``mod-*`` and rehearsal/test namespaces, so a
    runtime artifact publication can never be mistaken for an app release.
    """
    if not isinstance(value, str) or RUNTIME_VERSION.fullmatch(value) is None:
        return False, "version must be runtime-vMAJOR.MINOR.PATCH"
    plain = value[len("runtime-v"):]
    if any(part.lower() in RESERVED_PRERELEASE for part in plain.split(".")):
        return False, "rehearsal/test versions are never published"
    return True, "independent runtime version"


def build_script_for(artifact, root=None):
    """Allowlisted build wrapper for a publishable artifact kind.

    Fail closed if the wrapper is missing on disk: a resolved-but-absent script
    must never be handed to the workflow's build step. ``root`` is injectable
    so offline fixtures can exercise the failure path without touching main.
    """
    if artifact not in BUILD_SCRIPTS:
        raise ValueError(f"No verified build script for artifact {artifact!r}")
    relative = BUILD_SCRIPTS[artifact]
    base = Path(root) if root is not None else ROOT
    if not (base / relative).is_file():
        raise ValueError(f"Allowlisted build script is missing: {relative}")
    return relative


def resolve_build_delegate(artifact, root=None):
    """The real main entry point a wrapper delegates to; fail closed if absent.

    Resolution is read-only: it never imports, executes or mutates the delegate.
    """
    if artifact not in BUILD_DELEGATES:
        raise ValueError(f"No verified build delegate for artifact {artifact!r}")
    relative = BUILD_DELEGATES[artifact]
    base = Path(root) if root is not None else ROOT
    if not (base / relative).is_file():
        raise ValueError(f"Build delegate is missing on main: {relative}")
    return relative


def preflight_build(artifact, root=None):
    """Prove the build step is REACHABLE without executing any live tool.

    Resolves both the allowlisted wrapper and its real delegate and checks that
    both files exist. No QEMU, LXC, systemd, host provisioning, network or
    release operation is performed. Returns (ok, reason, decision).
    """
    decision = {"artifact": artifact}
    try:
        decision["build_script"] = build_script_for(artifact, root=root)
    except ValueError as error:
        return False, str(error), decision
    try:
        decision["delegate"] = resolve_build_delegate(artifact, root=root)
    except ValueError as error:
        return False, str(error), decision
    decision["build_script_exists"] = True
    decision["delegate_exists"] = True
    return True, "build entry point and delegate resolved offline", decision


# --- Identity assertion ------------------------------------------------------

def parse_identity_assertion(text):
    """Parse the operator identity assertion into a strict field mapping.

    The assertion binds the publication to an exact version, commit, artifact,
    project owner and publisher. Unknown or missing fields are refused; this is
    an identity claim, not a secret and not a credential.
    """
    if not isinstance(text, str):
        raise ValueError("identity assertion must be text")
    lines = [line.strip() for line in text.splitlines() if line.strip()]
    lines = [line for line in lines if not line.startswith("#")]
    if not lines or lines[0] != IDENTITY_HEADER:
        raise ValueError("identity assertion has an unknown or missing header")
    fields = {}
    for line in lines[1:]:
        if ":" not in line:
            raise ValueError("identity assertion line is not key: value")
        key, value = line.split(":", 1)
        key, value = key.strip(), value.strip()
        if key in fields:
            raise ValueError(f"duplicate identity field {key}")
        fields[key] = value
    if set(fields) != IDENTITY_FIELDS:
        missing = sorted(IDENTITY_FIELDS - set(fields))
        extra = sorted(set(fields) - IDENTITY_FIELDS)
        raise ValueError(
            f"identity fields mismatch (missing={missing}, unknown={extra})")
    if not fields["publisher"] or not fields["statement"]:
        raise ValueError("publisher and statement must not be empty")
    return fields


def check_identity_assertion(text, version, artifact, commit, owner=None):
    """Return (ok, reason, fields) for an assertion against dispatch inputs."""
    try:
        fields = parse_identity_assertion(text)
    except ValueError as error:
        return False, str(error), {}
    expected_owner = owner or project_owner()
    if fields["version"] != version:
        return False, "identity assertion version does not match dispatch", fields
    if fields["artifact"] != artifact:
        return False, "identity assertion artifact does not match dispatch", fields
    if fields["commit"] != commit:
        return False, "identity assertion commit does not match trusted SHA", fields
    if fields["owner"].lower() != expected_owner.lower():
        return False, "identity assertion owner is not the project owner", fields
    if FULL_SHA.fullmatch(fields["commit"]) is None:
        return False, "identity assertion commit is not a full 40-hex SHA", fields
    return True, "identity assertion bound to version, commit, artifact and owner", fields


# --- Trusted main SHA verification ------------------------------------------

def _git_ancestor(commit):
    try:
        subprocess.run(
            ["git", "merge-base", "--is-ancestor", commit, "origin/main"],
            check=True, cwd=ROOT, stdout=subprocess.DEVNULL,
            stderr=subprocess.DEVNULL)
        return True
    except (subprocess.CalledProcessError, OSError):
        return False


def _push_ci_run(commit):
    """Read-only exact-commit push CI lookup on the default branch."""
    output = subprocess.run(
        ["gh", "run", "list", "--workflow", "ci.yml", "--event", "push",
         "--branch", "main", "--commit", commit, "--json", "status,conclusion",
         "--limit", "1"],
        check=True, cwd=ROOT, text=True, capture_output=True)
    return json.loads(output.stdout)


def verify_main_ci(commit, runs_json=None, ancestor_checker=None, ci_reader=None):
    """The exact commit must be an ancestor of main AND have green push CI.

    ``ci_verified`` consumed by the gate must come from this function; an
    operator checkbox cannot substitute for it. Observers are injectable so
    tests run fully offline without git or GitHub access.
    """
    if not isinstance(commit, str) or FULL_SHA.fullmatch(commit) is None:
        return False, "trusted SHA must be a full 40-hex commit"
    ancestor = ancestor_checker or _git_ancestor
    if not ancestor(commit):
        return False, "trusted SHA is not an ancestor of main"
    reader = ci_reader or _push_ci_run
    try:
        runs = runs_json if runs_json is not None else reader(commit)
    except (subprocess.CalledProcessError, ValueError, TypeError, OSError):
        return False, "CI lookup unavailable; fail closed"
    if not runs or runs[0] != {"conclusion": "success", "status": "completed"}:
        return False, "no successful completed push CI for the exact commit"
    return True, "exact main CI verified"


# --- The single publication boundary ----------------------------------------

def publication_gate(event_name, publish_requested, version, artifact, trusted_sha,
                     identity_assertion, ci_verified, ref,
                     owner=None, identity_checker=None):
    """Return (allowed, reason, decision) for any runtime-artifact write.

    Every condition is fail-closed. ``ci_verified`` must be the output of
    :func:`verify_main_ci`, not a raw dispatch input. No condition here writes
    anything; the workflow uses the decision to gate staging and publication.
    """
    decision = {"version": version, "artifact": artifact, "commit": trusted_sha}
    if event_name != "workflow_dispatch":
        return False, f"{event_name} events stage only; publication needs an explicit workflow_dispatch", decision
    if ref != TRUSTED_REF:
        return False, "runtime publication is only valid on the trusted main ref", decision
    if str(publish_requested).strip().lower() != "true":
        return False, "publication needs publish=true (dispatch without it is a dry run)", decision
    ok, reason = valid_runtime_version(version)
    if not ok:
        return False, reason, decision
    if artifact not in VERIFIED_ARTIFACTS:
        return False, f"{artifact!r} has no verified import/boot evidence; use the portable installer", decision
    if FULL_SHA.fullmatch(trusted_sha or "") is None:
        return False, "trusted SHA must be a full 40-hex commit", decision
    if str(ci_verified).strip().lower() != "true":
        return False, "green exact-commit main CI is required before any write", decision
    checker = identity_checker or (
        lambda text, v, a, c, o: check_identity_assertion(text, v, a, c, o))
    ok, reason, fields = checker(identity_assertion, version, artifact, trusted_sha, owner or project_owner())
    if not ok:
        return False, reason, decision
    decision["identity"] = fields
    decision["build_script"] = build_script_for(artifact)
    return True, "explicit trusted dispatch with verified SHA, CI and bound identity", decision


def runtime_publication_allowed(event_name, publish_requested, version):
    """Small ADR-0033-shaped boundary used by fixtures and documentation."""
    if event_name != "workflow_dispatch":
        return False, f"{event_name} events stage only"
    if str(publish_requested).strip().lower() != "true":
        return False, "publication needs publish=true"
    return valid_runtime_version(version)


def assert_no_app_release(version, artifact=None):
    """Refuse app/module version domains so runtime writes never touch a release."""
    if isinstance(version, str) and (version.startswith("mod-") or
                                     re.fullmatch(r"v\d+\.\d+\.\d+.*", version)):
        raise ValueError("runtime artifacts use an independent version domain; no app release")
    ok, reason = valid_runtime_version(version)
    if not ok:
        raise ValueError(reason)
    if artifact is not None and artifact not in VERIFIED_ARTIFACTS:
        raise ValueError(f"unverified artifact {artifact!r} cannot be published")


# --- Deterministic integrity records ----------------------------------------

def sha256_bytes(data):
    return hashlib.sha256(data).hexdigest()


def sha256_file(path):
    digest = hashlib.sha256()
    with Path(path).open("rb") as handle:
        for chunk in iter(lambda: handle.read(1024 * 1024), b""):
            digest.update(chunk)
    return digest.hexdigest()


def _relative(path, root):
    path = Path(path)
    return path.relative_to(root).as_posix() if root else path.name


def checksum_manifest(paths, root=None):
    """Deterministic ``sha256sum -c`` compatible manifest, sorted by relpath."""
    rows = sorted((_relative(path, root), sha256_file(path)) for path in paths)
    return "".join(f"{digest}  {name}\n" for name, digest in rows)


def parse_checksum_manifest(text):
    """Strictly parse a checksum manifest; refuse malformed or duplicate rows."""
    entries = {}
    for line in text.splitlines():
        if not line.strip():
            continue
        match = re.fullmatch(r"([0-9a-f]{64})  (\S.*)", line)
        if not match:
            raise ValueError(f"malformed checksum line: {line!r}")
        digest, name = match.groups()
        if name in entries:
            raise ValueError(f"duplicate checksum entry: {name}")
        entries[name] = digest
    if not entries:
        raise ValueError("checksum manifest is empty")
    return entries


def verify_checksum_manifest(text, root):
    """Verify every listed file. Returns (ok, problems)."""
    problems = []
    try:
        entries = parse_checksum_manifest(text)
    except ValueError as error:
        return False, [str(error)]
    for name, expected in entries.items():
        path = Path(root) / name
        if not path.is_file():
            problems.append(f"missing file: {name}")
        elif sha256_file(path) != expected:
            problems.append(f"checksum mismatch: {name}")
    expected_names = set(entries)
    actual_names = {
        path.relative_to(root).as_posix()
        for path in Path(root).rglob("*") if path.is_file()
    }
    for extra in sorted(actual_names - expected_names - INTEGRITY_RECORDS):
        problems.append(f"unlisted file in staged bundle: {extra}")
    return (not problems), problems


def build_sbom(version, artifact, commit, paths, root=None, owner=None, repository=None):
    """Deterministic CycloneDX 1.5 JSON describing one staged artifact bundle."""
    ok, reason = valid_runtime_version(version)
    if not ok:
        raise ValueError(reason)
    if artifact not in VERIFIED_ARTIFACTS:
        raise ValueError(f"unverified artifact {artifact!r}")
    if FULL_SHA.fullmatch(commit or "") is None:
        raise ValueError("SBOM requires a full 40-hex source commit")
    repo = repository or os.environ.get("GITHUB_REPOSITORY", DEFAULT_REPOSITORY)
    owner_name = owner or project_owner(repo)
    uid = str(uuid.uuid5(uuid.NAMESPACE_URL, f"{repo}/{artifact}/{version}/{commit}"))
    components = []
    for path in paths:
        rel = _relative(path, root)
        components.append({
            "type": "file",
            "name": rel,
            "bom-ref": f"file:{rel}",
            "hashes": [{"alg": "SHA-256", "content": sha256_file(path)}],
        })
    components.sort(key=lambda item: item["name"])
    return {
        "bomFormat": "CycloneDX",
        "specVersion": "1.5",
        "serialNumber": f"urn:uuid:{uid}",
        "version": 1,
        "metadata": {
            "component": {
                "type": "application",
                "name": f"carbonpanel-runtime-{artifact}",
                "version": version[len("runtime-v"):],
                "bom-ref": f"runtime:{artifact}:{version}",
            },
            "properties": [
                {"name": "carbonpanel:runtime:owner", "value": owner_name},
                {"name": "carbonpanel:runtime:repository", "value": repo.lower()},
                {"name": "carbonpanel:runtime:source-commit", "value": commit},
                {"name": "carbonpanel:runtime:version-domain", "value": "runtime-v"},
            ],
        },
        "components": components,
    }


def sbom_json(sbom):
    """Stable serialisation: reproducible without timestamps or host paths."""
    return json.dumps(sbom, indent=2, sort_keys=True, ensure_ascii=False) + "\n"


def validate_sbom_document(document, version, artifact, commit):
    """Minimal structural validation of a generated SBOM (no external deps)."""
    required = {"bomFormat", "specVersion", "serialNumber", "version", "metadata", "components"}
    if not isinstance(document, dict) or not required <= set(document):
        return False, "SBOM is missing required top-level fields"
    if document["bomFormat"] != "CycloneDX" or document["specVersion"] != "1.5":
        return False, "SBOM format/version is not CycloneDX 1.5"
    metadata = document["metadata"]
    component = metadata.get("component", {}) if isinstance(metadata, dict) else {}
    if component.get("version") != version[len("runtime-v"):]:
        return False, "SBOM component version does not match the runtime version"
    props = {p.get("name"): p.get("value") for p in metadata.get("properties", [])
             if isinstance(p, dict)}
    if props.get("carbonpanel:runtime:source-commit") != commit:
        return False, "SBOM source commit does not match the trusted SHA"
    if not component.get("name", "").endswith(artifact):
        return False, "SBOM component does not match the artifact kind"
    for item in document["components"]:
        if not isinstance(item, dict) or not item.get("hashes"):
            return False, "SBOM file component has no hashes"
    return True, "SBOM structure and bindings are valid"


def expected_certificate_identity(repository=None, ref=None):
    """The Fulcio certificate identity for this keyless signing workflow.

    GitHub Actions OIDC certificates bind the workflow ref, NOT an operator's
    free-form label. This derives the exact identity consumers must pass to
    ``cosign verify-blob --certificate-identity`` from trusted inputs only:

      https://github.com/<repo>/.github/workflows/runtime-artifacts.yml@refs/heads/main

    Source: sigstore/cosign README, "Identity-based blob signing and
    verification"; GitHub OIDC reference for the ``workflow_ref`` claim.
    A non-trusted ref is refused so no feature/tag ref can claim this identity.
    """
    ref = ref or TRUSTED_REF
    if ref != TRUSTED_REF:
        raise ValueError("certificate identity is only defined for the trusted main ref")
    repo = (repository or os.environ.get("GITHUB_REPOSITORY", DEFAULT_REPOSITORY)).lower()
    if not re.fullmatch(r"[a-z0-9-]+/[a-z0-9._-]+", repo):
        raise ValueError("Invalid GITHUB_REPOSITORY for certificate identity")
    return f"https://github.com/{repo}/{WORKFLOW_PATH}@{ref}"


def signature_binding(version, artifact, commit, manifest_text, expected_identity,
                      signature, publisher_label=None):
    """Build the fail-closed signature provenance record for a manifest.

    ``expected_identity`` is the canonical OIDC workflow-ref identity derived by
    :func:`expected_certificate_identity`. ``publisher_label`` is informational
    operator metadata and is explicitly NOT a certificate identity; it is never
    validated as one and consumers must not use it to verify a signature.
    """
    if expected_identity != expected_certificate_identity():
        raise ValueError("signer identity must be the canonical OIDC workflow-ref identity")
    return {
        "version": version,
        "artifact": artifact,
        "commit": commit,
        "manifest_sha256": sha256_bytes(manifest_text.encode("utf-8")),
        "signer_identity": expected_identity,
        "publisher_label": publisher_label or "",
        "signature": signature,
    }


def verify_signature_binding(document, manifest_text, expected_identity):
    """Offline integrity/binding precondition; NOT a cryptographic verification.

    Cryptographic verification of the cosign keyless signature is the
    CONSUMER's step, documented in docs/node-runtime/verified-artifacts-install.md
    using ``cosign verify-blob --bundle ... --certificate-identity ...
    --certificate-oidc-issuer ...``. This offline check only confirms the record
    is well formed, bound to the exact manifest, names the canonical workflow
    identity and contains a non-empty signature. It fails closed otherwise.
    """
    required = {"version", "artifact", "commit", "manifest_sha256",
                "signer_identity", "signature"}
    if not isinstance(document, dict) or not required <= set(document):
        return False, "signature record is missing required fields"
    if document["manifest_sha256"] != sha256_bytes(manifest_text.encode("utf-8")):
        return False, "signature record manifest digest does not match the manifest"
    if document["signer_identity"] != expected_identity:
        return False, "signature record identity is not the canonical OIDC workflow-ref identity"
    if not isinstance(document["signature"], str) or not document["signature"].strip():
        return False, "signature is empty"
    return True, "signature record is bound to the manifest and workflow identity"


def verify_bundle(directory, version, artifact, commit, identity=None,
                  repository=None, manifest_name="SHA256SUMS",
                  sbom_name="sbom.cdx.json", signature_name="signature.json"):
    """Full offline precondition gate for a staged artifact bundle.

    Cryptographic signature verification is NOT performed here; it is the
    consumer's step (see the install guide). This only checks integrity records
    and their binding to the trusted OIDC workflow identity.
    """
    root = Path(directory)
    problems = []
    manifest_path = root / manifest_name
    sbom_path = root / sbom_name
    signature_path = root / signature_name
    for path in (manifest_path, sbom_path, signature_path):
        if not path.is_file():
            problems.append(f"missing required record: {path.name}")
    if problems:
        return False, problems
    manifest_text = manifest_path.read_text(encoding="utf-8")
    ok, issues = verify_checksum_manifest(manifest_text, root)
    problems.extend(issues)
    try:
        sbom = json.loads(sbom_path.read_text(encoding="utf-8"))
    except (ValueError, OSError):
        problems.append("SBOM is not valid JSON")
        sbom = None
    if sbom is not None:
        ok_sbom, issue = validate_sbom_document(sbom, version, artifact, commit)
        if not ok_sbom:
            problems.append(issue)
    try:
        signature = json.loads(signature_path.read_text(encoding="utf-8"))
    except (ValueError, OSError):
        problems.append("signature record is not valid JSON")
        signature = None
    if signature is not None:
        try:
            oidc_identity = expected_certificate_identity(repository)
        except ValueError as error:
            problems.append(str(error))
        else:
            ok_sig, issue = verify_signature_binding(signature, manifest_text, oidc_identity)
            if not ok_sig:
                problems.append(issue)
    return (not problems), problems


# --- CLI --------------------------------------------------------------------

def write_output(values):
    """Emit step outputs without ever writing into the repository."""
    path = os.environ.get("GITHUB_OUTPUT")
    if not path:
        return
    with open(path, "a", encoding="utf-8") as handle:
        for key, value in values.items():
            handle.write(f"{key}={value}\n")


def _print_json(values):
    print(json.dumps(values, indent=2, sort_keys=True))


