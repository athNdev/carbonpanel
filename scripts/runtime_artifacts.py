def _assertion_text(args):
    if getattr(args, "assertion_file", None):
        return Path(args.assertion_file).read_text(encoding="utf-8")
    return getattr(args, "assertion", "") or ""


def _artifact_files(directory, excluded):
    root = Path(directory)
    return sorted(path for path in root.rglob("*")
                  if path.is_file() and path.name not in excluded)


def main(argv=None):
    args = build_parser().parse_args(argv)
    if args.command == "verify-main-ci":
        runs = args.runs_json
        if runs:
            runs = json.loads(Path(runs).read_text(encoding="utf-8"))
        verified, reason = verify_main_ci(args.commit, runs_json=runs)
        values = {"verified": str(verified).lower(), "reason": reason, "commit": args.commit}
        _print_json(values)
        write_output(values)
        return 0 if verified else 1

    if args.command == "verify-identity":
        ok, reason, fields = check_identity_assertion(
            _assertion_text(args), args.version, args.artifact, args.commit, args.owner)
        _print_json({"verified": str(ok).lower(), "reason": reason, "identity": fields})
        return 0 if ok else 1

    if args.command == "gate":
        allowed, reason, decision = publication_gate(
            args.event, args.publish_input, args.version, args.artifact,
            args.trusted_sha, _assertion_text(args), args.ci_verified,
            args.ref, args.owner)
        values = {"allowed": str(allowed).lower(), "reason": reason,
                  "decision": json.dumps(decision, sort_keys=True)}
        _print_json(values)
        write_output(values)
        return 0  # a refusal is a clean, auditable dry run, not a crash

    if args.command == "build-script":
        print(build_script_for(args.artifact))
        return 0

    if args.command == "preflight-build":
        ok, reason, decision = preflight_build(args.artifact)
        _print_json({"reachable": str(ok).lower(), "reason": reason,
                     "decision": decision})
        return 0 if ok else 1

    if args.command == "assert-no-app-release":
        assert_no_app_release(args.version, args.artifact)
        print("independent runtime version confirmed; no app release touched")
        return 0

    if args.command == "checksums":
        excluded = INTEGRITY_RECORDS
        manifest = checksum_manifest(_artifact_files(args.dir, excluded), root=Path(args.dir))
        if args.output:
            Path(args.output).write_text(manifest, encoding="utf-8")
        else:
            sys.stdout.write(manifest)
        return 0

    if args.command == "verify-checksums":
        text = Path(args.manifest).read_text(encoding="utf-8")
        ok, problems = verify_checksum_manifest(text, args.dir)
        _print_json({"verified": str(ok).lower(), "problems": problems})
        return 0 if ok else 1

    if args.command == "sbom":
        excluded = INTEGRITY_RECORDS
        document = build_sbom(args.version, args.artifact, args.commit,
                              _artifact_files(args.dir, excluded), root=Path(args.dir),
                              owner=args.owner)
        text = sbom_json(document)
        if args.output:
            Path(args.output).write_text(text, encoding="utf-8")
        else:
            sys.stdout.write(text)
        return 0

    if args.command == "verify-bundle":
        ok, _, fields = check_identity_assertion(
            _assertion_text(args), args.version, args.artifact, args.commit, args.owner)
        if not ok:
            _print_json({"verified": "false", "problems": ["identity assertion invalid"]})
            return 1
        ok, problems = verify_bundle(args.dir, args.version, args.artifact,
                                     args.commit, fields)
        _print_json({"verified": str(ok).lower(), "problems": problems})
        return 0 if ok else 1
    return 2


if __name__ == "__main__":
    sys.exit(main())
