"""Deterministic, Docker-focused Docker Hub repository description.

The GitHub README is the source of truth for product content, but it is too
large for Docker Hub's 25,000-byte body limit once URL completion is applied.
This module derives a compact view from selected README sections, rewrites
relative links to absolute links, injects the current Stable marker from a
checked-in config, and proves the public body by reading it back from the
unauthenticated Docker Hub API.

It never touches registry tags, images, GitHub releases or deployed services.
"""
import argparse
import hashlib
import json
import os
from pathlib import Path
import posixpath
import re
import sys
import time
import urllib.error
import urllib.request

ROOT = Path(__file__).resolve().parent.parent
if str(ROOT) not in sys.path:
    sys.path.insert(0, str(ROOT))
from scripts import release as release_contract

LIVE_INDEX_URL = "https://carbonpanel.dev/version-index.json"

MAX_BODY_BYTES = 25000
HUB_REPO_RE = re.compile(r"^[A-Za-z0-9_.-]+/[A-Za-z0-9_.-]+$")
VERSION_RE = re.compile(r"^\d+\.\d+\.\d+(?:-[0-9A-Za-z.-]+)?$")
COMMIT_RE = re.compile(r"^[0-9a-f]{40}$")
IMAGE_SUFFIXES = frozenset({".bmp", ".gif", ".jpg", ".jpeg", ".png", ".svg", ".webp"})
ABSOLUTE_PREFIXES = ("http://", "https://", "mailto:", "data:", "#")
HEADING_RE = re.compile(r"^## (.+?)\s*$")
MARKDOWN_LINK_RE = re.compile(r"\]\(([^)\n]*)\)")
HTML_ATTR_RE = re.compile(r'(\b(?:href|src)=")([^"]+)(")')

HEADER = """\
<!-- Derived Docker Hub description. Generated by scripts/dockerhub_description.py; do not edit by hand. -->

# Carbon Panel

Self-hosted Minecraft server and modpack management with Docker. Build modpacks,
look after your servers, and keep every block on your own terms.

**Current Stable:** `{version}` (`{tag}`, commit `{commit_short}`, digest `{digest_short}`).
Install the pinned image: `docker pull {repository}:{version}`.
`:latest` is a moving alias; there is no `:stable` tag. See [releases](https://github.com/{github_repository}/releases).

[Full README](https://github.com/{github_repository}/blob/{ref}/README.md) · [Showcase captures](https://github.com/{github_repository}/tree/{showcase_ref}/assets/showcase) · [Documentation](https://carbonpanel.dev/docs/) · [MCP guide]({mcp_guide_url}) · [Docker image](https://hub.docker.com/r/{repository})

> Condensed Docker-focused view. The full README carries the complete feature,
> MCP and development detail.
"""

REQUIRED_KEYS = (
    "repository", "github_repository", "ref", "showcase_ref", "version_index",
    "short_description", "mcp_guide_url", "sections", "max_bytes",
)

# The README Quick Start paragraph historically embedded the then-current Stable
# version. Suppress that sentence so a later promotion cannot leave this derived
# body on an obsolete release.
STALE_STABLE_RE = re.compile(
    r"The verified stable is `[^`]+` \(`[^`]+`\),.*?minor alias\.",
    re.DOTALL,
)
STALE_STABLE_REPLACEMENT = (
    "Prereleases never move `latest` or a minor alias. "
    "See the Current Stable marker above for the published version."
)
VERSION_IN_BODY_RE = re.compile(r"\b\d+\.\d+\.\d+\b")


class DescriptionError(Exception):
    """A configuration, generation, fetch or verification failure."""


def load_config(path):
    """Read and validate the checked-in description config."""
    try:
        config = json.loads(Path(path).read_text(encoding="utf-8"))
    except (OSError, ValueError) as error:
        raise DescriptionError("cannot read description config: " + str(error)) from error
    if not isinstance(config, dict):
        raise DescriptionError("description config must be a JSON object")
    missing = [key for key in REQUIRED_KEYS if key not in config]
    if missing:
        raise DescriptionError("description config missing key(s): " + ", ".join(missing))
    for key in ("repository", "github_repository", "ref", "showcase_ref",
                "version_index", "short_description", "mcp_guide_url"):
        if not isinstance(config[key], str) or not config[key].strip():
            raise DescriptionError("description config key must be a non-empty string: " + key)
    if not HUB_REPO_RE.fullmatch(config["repository"]):
        raise DescriptionError("invalid Docker Hub repository: " + config["repository"])
    if not HUB_REPO_RE.fullmatch(config["github_repository"]):
        raise DescriptionError("invalid GitHub repository: " + config["github_repository"])
    if not config["mcp_guide_url"].startswith("https://"):
        raise DescriptionError("mcp_guide_url must be an absolute https URL")
    if not isinstance(config["sections"], list) or not config["sections"] \
            or not all(isinstance(item, str) and item.strip() for item in config["sections"]):
        raise DescriptionError("sections must be a non-empty list of heading strings")
    limit = config["max_bytes"]
    if not isinstance(limit, int) or isinstance(limit, bool) or not 1 <= limit <= MAX_BODY_BYTES:
        raise DescriptionError("max_bytes must be an integer between 1 and " + str(MAX_BODY_BYTES))
    if len(config["short_description"].encode("utf-8")) > 100:
        raise DescriptionError("short_description exceeds Docker Hub's 100-byte limit")
    return config


DIGEST_RE = re.compile(r"^sha256:[0-9a-f]{64}$")


def semver_key(version):
    """Ordering key for a user-facing SemVer (legacy and product tags agree)."""
    core = str(version).split("-", 1)[0]
    parts = core.split(".")
    if len(parts) != 3 or not all(part.isdigit() for part in parts):
        raise DescriptionError("invalid SemVer for Stable ordering: " + str(version))
    return tuple(int(part) for part in parts)


def stable_identity(index, source):
    """Validate and extract a Stable identity using the release tag contract.

    Both the legacy ``v1.0.40`` tag and current ``carbonpanel-vMAJOR.MINOR.PATCH``
    product tags are parsed by scripts/release.py, so no local tag/version
    equality rule can reject a promoted release.
    """
    if not isinstance(index, dict):
        raise DescriptionError(source + " version index is not an object")
    stable = index.get("stable")
    channel = (index.get("channels") or {}).get("stable") or {}
    if not isinstance(stable, dict) or not isinstance(channel, dict):
        raise DescriptionError(source + " has no stable channel")
    image = channel.get("image") or {}
    tag = stable["tag"] if "tag" in stable else channel.get("tag")
    version = stable["version"] if "version" in stable else channel.get("version")
    commit = stable["commit"] if "commit" in stable else channel.get("commit")
    digest = stable["digest"] if "digest" in stable else image.get("digest")
    image_tag = stable["image_tag"] if "image_tag" in stable else image.get("tag")
    for name, value in (("tag", tag), ("version", version), ("commit", commit),
                        ("digest", digest), ("image_tag", image_tag)):
        if not value:
            raise DescriptionError(source + " stable is missing " + name)
    if release_contract.version_from_release_tag(tag) is None:
        raise DescriptionError(source + " stable tag is not a recognised release tag: " + str(tag))
    parsed_version = release_contract.display_version(tag)
    if parsed_version != version:
        raise DescriptionError(source + " stable tag/version disagree: "
                               + str(tag) + " / " + str(version))
    if not COMMIT_RE.fullmatch(commit):
        raise DescriptionError(source + " stable commit is invalid: " + str(commit))
    if not DIGEST_RE.fullmatch(digest):
        raise DescriptionError(source + " stable image digest is invalid: " + str(digest))
    consistency = (
        ("channel commit", channel.get("commit"), commit),
        ("image revision", image.get("revision"), commit),
        ("image digest", image.get("digest"), digest),
        ("image tag", image.get("tag"), image_tag),
    )
    for label, observed, expected in consistency:
        if observed and observed != expected:
            raise DescriptionError(source + " stable " + label
                                   + " disagrees with its identity")
    promotion = channel.get("promotion") or {}
    if promotion.get("state") != "published" or promotion.get("promoted") is not True:
        raise DescriptionError(source + " stable channel is not published")
    semver_key(version)
    return {
        "version": version, "tag": tag, "commit": commit,
        "image_tag": image_tag, "digest": digest, "source": source,
    }


def resolve_stable(index_path):
    """Resolve the checked-in Stable baseline from the product version contract."""
    try:
        index = json.loads(Path(index_path).read_text(encoding="utf-8"))
    except (OSError, ValueError) as error:
        raise DescriptionError("cannot read version contract index: " + str(error)) from error
    return stable_identity(index, "checked-in version index")


def fetch_live_index(opener=None, url=LIVE_INDEX_URL, timeout=30):
    """Fetch the published version index that reconciles carbonpanel.dev."""
    opener = opener or urllib.request.urlopen
    try:
        with opener(url, timeout=timeout) as response:
            return json.load(response)
    except urllib.error.HTTPError as error:
        raise DescriptionError("live version index returned HTTP " + str(error.code)
                               + "; cannot confirm the published Stable") from error
    except urllib.error.URLError as error:
        raise DescriptionError("could not reach the published version index: "
                               + str(error.reason)) from error
    except (ValueError, TypeError) as error:
        raise DescriptionError("published version index is not valid JSON: "
                               + str(error)) from error


def choose_stable(baseline, live):
    """The live published identity is authoritative for a public write.

    A checked-in baseline that is merely newer than public Stable is a
    pre-promotion state: advertising it would put an unpromoted identity on the
    public page. Fail closed instead of guessing. Offline fixture mode may
    explicitly skip the live index; production never does.
    """
    if not live:
        return baseline
    if semver_key(live["version"]) < semver_key(baseline["version"]):
        raise DescriptionError(
            "checked-in Stable " + baseline["version"] + " is newer than public Stable "
            + live["version"] + "; refusing to advertise a pre-promotion identity")
    return live


def resolve_main_sha(repository, event_name, event_sha, opener=None, timeout=30):
    """Resolve the target main commit before checkout from the GitHub refs API.

    Schedules, dispatches and workflow_run events run in an empty workspace, so
    this path must not depend on a local git checkout or an `origin` remote.
    """
    if event_name == "push":
        if not re.fullmatch(r"[0-9a-f]{40}", event_sha or ""):
            raise DescriptionError("push event has no full commit SHA")
        return event_sha
    if not HUB_REPO_RE.fullmatch(repository):
        raise DescriptionError("invalid GitHub repository for main resolution: " + str(repository))
    opener = opener or urllib.request.urlopen
    url = "https://api.github.com/repos/{}/git/ref/heads/main".format(repository)
    try:
        with opener(url, timeout=timeout) as response:
            payload = json.load(response)
    except urllib.error.HTTPError as error:
        raise DescriptionError("GitHub refs API returned HTTP " + str(error.code)
                               + " for " + url) from error
    except urllib.error.URLError as error:
        raise DescriptionError("could not reach the GitHub refs API: " + str(error.reason)) from error
    sha = (payload.get("object") or {}).get("sha")
    if not re.fullmatch(r"[0-9a-f]{40}", sha or ""):
        raise DescriptionError("GitHub refs API did not return a full main commit SHA")
    return sha


def require_same_commit(expected, observed, context):
    """Fail closed when main advanced during a run (promotion race)."""
    if not expected or not observed:
        raise DescriptionError("cannot verify " + context + ": missing commit id")
    if expected != observed:
        raise DescriptionError(
            "{}: main advanced from {} to {} during this run; refusing to publish "
            "a stale Stable marker. The next scheduled sync will reconcile.".format(
                context, expected, observed))


def split_sections(readme_text):
    """Map each top-level ``## `` heading to its Markdown body."""
    sections = {}
    title = None
    buffer = []
    for line in readme_text.replace("\r\n", "\n").split("\n"):
        match = HEADING_RE.match(line)
        if match:
            if title is not None:
                sections[title] = "\n".join(buffer).strip("\n")
            title = match.group(1).strip()
            buffer = [line]
        elif title is not None:
            buffer.append(line)
    if title is not None:
        sections[title] = "\n".join(buffer).strip("\n")
    return sections


def absolute_target(target, github_repository, ref):
    """Rewrite one relative link target to a stable absolute GitHub URL."""
    text = target.strip()
    if not text or text.startswith(ABSOLUTE_PREFIXES):
        return target
    # Preserve an optional Markdown title after the target.
    path, separator, tail = text.partition(" ")
    if path.startswith("<") and path.endswith(">"):
        path = path[1:-1]
    if path.startswith(ABSOLUTE_PREFIXES) or path in (".", "/"):
        return target
    without_fragment, fragment_marker, fragment = path.partition("#")
    clean = posixpath.normpath(without_fragment.replace("\\", "/"))
    if not clean or clean == "." or clean.startswith("..") or clean.startswith("/"):
        # Do not escape the repository or invent a URL for an empty path.
        return target
    suffix = posixpath.splitext(clean)[1].lower()
    if suffix in IMAGE_SUFFIXES:
        absolute = "https://raw.githubusercontent.com/{}/{}/{}".format(
            github_repository, ref, clean)
    else:
        absolute = "https://github.com/{}/blob/{}/{}".format(
            github_repository, ref, clean)
    if fragment_marker:
        absolute += "#" + fragment
    if separator:
        absolute += separator + tail
    return absolute


def absolute_links(text, github_repository, ref):
    """Rewrite relative Markdown/HTML links, leaving fenced code untouched."""
    output = []
    fenced = False
    for line in text.split("\n"):
        if line.lstrip().startswith("```"):
            fenced = not fenced
            output.append(line)
            continue
        if fenced:
            output.append(line)
            continue
        line = MARKDOWN_LINK_RE.sub(
            lambda match: "](" + absolute_target(
                match.group(1), github_repository, ref) + ")",
            line)
        line = HTML_ATTR_RE.sub(
            lambda match: match.group(1) + absolute_target(
                match.group(2), github_repository, ref) + match.group(3),
            line)
        output.append(line)
    return "\n".join(output)


def build_body(config, readme_text, stable):
    """Compose the deterministic Docker-focused description body."""
    parsed = split_sections(readme_text)
    missing = [name for name in config["sections"] if name not in parsed]
    if missing:
        raise DescriptionError(
            "README.md is missing configured section(s): " + "; ".join(missing)
            + ". Update docs/dockerhub-description.json deliberately.")
    parts = [HEADER.format(
        version=stable["version"],
        tag=stable["tag"],
        commit_short=stable["commit"][:12],
        digest_short=stable["digest"][:19] + "…",
        repository=config["repository"],
        github_repository=config["github_repository"],
        ref=config["ref"],
        showcase_ref=config["showcase_ref"],
        mcp_guide_url=config["mcp_guide_url"],
    )]
    for name in config["sections"]:
        section = STALE_STABLE_RE.sub(STALE_STABLE_REPLACEMENT, parsed[name])
        parts.append(absolute_links(section, config["github_repository"], config["ref"]))
    body = "\n\n".join(parts).strip("\n") + "\n"
    # A promotion must not leave an older hardcoded version in a README section.
    header_end = body.index("\n\n## ")
    header, derived = body[:header_end], body[header_end:]
    found = set(VERSION_IN_BODY_RE.findall(derived))
    stale = sorted(found - {stable["version"]})
    if stale:
        raise DescriptionError(
            "README sections in the derived body still advertise stable version(s) "
            + ", ".join(stale) + " while the published contract is "
            + stable["version"] + ". Suppress those sentences in the generator "
            "before publishing.")
    enforce_limit(body, config["max_bytes"])
    return body


def enforce_limit(body, limit):
    """Fail closed with a per-section breakdown when the body will be truncated."""
    size = len(body.encode("utf-8"))
    if size <= limit:
        return size
    details = []
    for section in split_sections(body):
        details.append("{}: {}".format(section[:60], len(
            ("## " + section + "\n" + split_sections(body)[section]).encode("utf-8"))))
    raise DescriptionError(
        "generated body is {} UTF-8 bytes, over the {}-byte limit. "
        "Reduce configured sections before publishing. Sizes: {}".format(
            size, limit, "; ".join(details)))


def body_sha256(body):
    return hashlib.sha256(body.encode("utf-8")).hexdigest()


def read_body(path):
    try:
        return Path(path).read_text(encoding="utf-8").replace("\r\n", "\n")
    except OSError as error:
        raise DescriptionError("cannot read expected body: " + str(error)) from error


def fetch_repository(repository, opener=None, timeout=30):
    """Fetch public repository metadata; never uses or prints credentials."""
    opener = opener or urllib.request.urlopen
    url = "https://hub.docker.com/v2/repositories/{}/".format(repository)
    try:
        with opener(url, timeout=timeout) as response:
            return json.load(response)
    except urllib.error.HTTPError as error:
        raise DescriptionError(
            "Docker Hub API returned HTTP {} for {}. Check that the repository "
            "name is correct and public.".format(error.code, url)) from error
    except urllib.error.URLError as error:
        raise DescriptionError("could not reach the public Docker Hub API: "
                               + str(error.reason)) from error
    except (ValueError, TypeError) as error:
        raise DescriptionError("Docker Hub API returned an unreadable response: "
                               + str(error)) from error


def published_short_description(data):
    """Docker Hub v2 returns the tagline as `description`, not `short_description`."""
    return data.get("description") or data.get("short_description")


def live_description(repository, live_file=None, opener=None):
    if live_file:
        return json.loads(Path(live_file).read_text(encoding="utf-8"))
    return fetch_repository(repository, opener=opener)


def first_difference(expected, live):
    """Return a compact first-line difference for actionable CI logs."""
    expected_lines = expected.split("\n")
    live_lines = (live or "").split("\n")
    for index in range(max(len(expected_lines), len(live_lines))):
        left = expected_lines[index] if index < len(expected_lines) else "<missing>"
        right = live_lines[index] if index < len(live_lines) else "<missing>"
        if left != right:
            return index + 1, left[:160], right[:160]
    return None


def compare(expected, live):
    """Return (matches, human-readable explanation)."""
    if live is None:
        return False, "no full_description is published on Docker Hub"
    live = live.replace("\r\n", "\n")
    if live == expected:
        return True, "public body matches the generated body exactly"
    difference = first_difference(expected, live)
    if difference:
        line, expected_line, live_line = difference
        return False, ("first difference at line {}: expected {!r}, live {!r} "
                       "(expected {} UTF-8 bytes, live {} UTF-8 bytes)".format(
                           line, expected_line, live_line,
                           len(expected.encode("utf-8")),
                           len(live.encode("utf-8"))))
    return False, "public body differs from the generated body"


def read_back_with_retry(expected, repository, opener=None, attempts=10, delay=6, sleep=None):
    """Bounded propagation tolerance for the public Docker Hub read-back."""
    sleep = sleep or time.sleep
    data = None
    explanation = ""
    for attempt in range(1, attempts + 1):
        data = fetch_repository(repository, opener=opener)
        matches, explanation = compare(expected, data.get("full_description"))
        if matches:
            return data, True, explanation, attempt - 1
        if attempt < attempts:
            sleep(delay)
    return data, False, explanation, attempts - 1


def require_credentials():
    """Fail closed when a write is needed, without printing any secret value."""
    user = os.environ.get("DOCKER_HUB_USERNAME") or os.environ.get("DOCKERHUB_USERNAME")
    password = (os.environ.get("DOCKER_HUB_PASSWORD")
                or os.environ.get("DOCKERHUB_TOKEN")
                or os.environ.get("DOCKER_HUB_TOKEN"))
    problems = []
    if not user:
        problems.append("DOCKER_HUB_USERNAME (or DOCKERHUB_USERNAME)")
    if not password:
        problems.append("DOCKER_HUB_PASSWORD (or DOCKERHUB_TOKEN)")
    if problems:
        raise DescriptionError("Docker Hub write requires missing secret(s): "
                               + ", ".join(problems))


def emit_outputs(values):
    """Append step outputs for GitHub Actions when running inside a job."""
    output_path = os.environ.get("GITHUB_OUTPUT")
    if not output_path:
        return
    with open(output_path, "a", encoding="utf-8") as handle:
        for key, value in values.items():
            handle.write("{}={}\n".format(key, value))


def command_generate(arguments):
    config = load_config(arguments.config)
    baseline = resolve_stable(arguments.version_index or ROOT / config["version_index"])
    if arguments.live_index:
        live = stable_identity(json.loads(Path(arguments.live_index).read_text(
            encoding="utf-8")), "live published version index")
    elif arguments.skip_live_index:
        live = None
    else:
        # Production is fail-closed: no live identity means no public write.
        # A stale baseline after a promotion must never be published.
        live = stable_identity(fetch_live_index(), "live published version index")
    stable = choose_stable(baseline, live)
    readme = Path(arguments.readme).read_text(encoding="utf-8")
    body = build_body(config, readme, stable)
    Path(arguments.output).write_text(body, encoding="utf-8", newline="\n")
    summary = {
        "repository": config["repository"],
        "stable_version": stable["version"],
        "stable_tag": stable["tag"],
        "stable_commit": stable["commit"],
        "stable_digest": stable["digest"],
        "stable_source": stable["source"],
        "bytes": len(body.encode("utf-8")),
        "sha256": body_sha256(body),
        "output": arguments.output,
    }
    print(json.dumps(summary, sort_keys=True))
    emit_outputs({
        "short_description": config["short_description"],
        "expected_bytes": summary["bytes"],
        "expected_sha256": summary["sha256"],
        "stable_version": stable["version"],
        "stable_commit": stable["commit"],
        "stable_source": stable["source"],
    })


def command_assert_head(arguments):
    require_same_commit(arguments.expected, arguments.observed, "main commit guard")
    print("main head is unchanged at " + arguments.expected)
    return 0


def command_resolve_main(arguments):
    sha = resolve_main_sha(arguments.repository, arguments.event, arguments.event_sha)
    print(sha)
    emit_outputs({"sha": sha})
    return 0


def command_check(arguments):
    config = load_config(arguments.config)
    expected = read_body(arguments.expected)
    data = live_description(config["repository"], arguments.live_file)
    live = data.get("full_description")
    matches, explanation = compare(expected, live)
    short_ok = published_short_description(data) == config["short_description"]
    changed = (not matches) or (not short_ok) or arguments.force
    # Keep stdout clean: this step's output file is written by emit_outputs.
    print(explanation, file=sys.stderr)
    print("expected {} UTF-8 bytes, live {} UTF-8 bytes, short_description_ok={}".format(
        len(expected.encode("utf-8")),
        len((live or "").encode("utf-8")),
        str(short_ok).lower()), file=sys.stderr)
    emit_outputs({
        "changed": str(changed).lower(),
        "matches": str(matches).lower(),
        "expected_bytes": len(expected.encode("utf-8")),
        "live_bytes": len((live or "").encode("utf-8")),
        "expected_sha256": body_sha256(expected),
        "short_description_ok": str(short_ok).lower(),
    })
    return 0


def command_verify(arguments):
    config = load_config(arguments.config)
    expected = read_body(arguments.expected)
    if arguments.live_file:
        data = live_description(config["repository"], arguments.live_file)
        matches, explanation = compare(expected, data.get("full_description"))
        waits = 0
    else:
        data, matches, explanation, waits = read_back_with_retry(
            expected, config["repository"],
            attempts=arguments.attempts, delay=arguments.delay)
    print(explanation)
    if waits:
        print("public read-back matched after {} propagation wait(s)".format(waits))
    if not matches:
        print("::error::Docker Hub public description drifted from the generated body")
        return 1
    if arguments.check_short_description and \
            published_short_description(data) != config["short_description"]:
        print("::error::Docker Hub short description does not match the config")
        return 1
    print("verified {} UTF-8 bytes, sha256 {}".format(
        len(expected.encode("utf-8")), body_sha256(expected)))
    return 0


def command_require_credentials(arguments):
    require_credentials()
    print("Docker Hub write credentials are present")
    return 0


def build_parser():
    parser = argparse.ArgumentParser(description=__doc__)
    commands = parser.add_subparsers(dest="command", required=True)

    generate = commands.add_parser("generate", help="derive the expected body")
    generate.add_argument("--config", default="docs/dockerhub-description.json")
    generate.add_argument("--readme", default="README.md")
    generate.add_argument("--version-index", help="override the version contract index (fixtures)")
    generate.add_argument("--live-index", help="offline fixture: published version index")
    generate.add_argument("--skip-live-index", action="store_true",
                          help="use only the checked-in baseline (offline fixtures)")
    generate.add_argument("--output", required=True)
    generate.set_defaults(handler=command_generate)

    check = commands.add_parser("check", help="compare the public body without failing on drift")
    check.add_argument("--config", default="docs/dockerhub-description.json")
    check.add_argument("--expected", required=True)
    check.add_argument("--live-file", help="offline fixture: JSON repository response")
    check.add_argument("--force", action="store_true", help="report changed=true even on a match")
    check.set_defaults(handler=command_check)

    verify = commands.add_parser("verify", help="fail CI unless the public body matches")
    verify.add_argument("--config", default="docs/dockerhub-description.json")
    verify.add_argument("--expected", required=True)
    verify.add_argument("--live-file", help="offline fixture: JSON repository response")
    verify.add_argument("--check-short-description", action="store_true")
    verify.add_argument("--attempts", type=int, default=10)
    verify.add_argument("--delay", type=float, default=6.0)
    verify.set_defaults(handler=command_verify)

    main_ref = commands.add_parser("resolve-main", help="resolve the target main commit before checkout")
    main_ref.add_argument("--repository", required=True)
    main_ref.add_argument("--event", required=True)
    main_ref.add_argument("--event-sha", default="")
    main_ref.set_defaults(handler=command_resolve_main)

    credentials = commands.add_parser("require-credentials", help="preflight write credentials")
    credentials.set_defaults(handler=command_require_credentials)

    head = commands.add_parser("assert-head", help="refuse to publish if main advanced")
    head.add_argument("--expected", required=True)
    head.add_argument("--observed", required=True)
    head.set_defaults(handler=command_assert_head)
    return parser


def main(argv=None):
    arguments = build_parser().parse_args(argv)
    try:
        return arguments.handler(arguments) or 0
    except DescriptionError as error:
        print("::error::" + str(error), file=sys.stderr)
        return 2


if __name__ == "__main__":
    sys.exit(main())
