import { test } from 'node:test';
import assert from 'node:assert/strict';
import { spawnSync } from 'node:child_process';
import { copyFileSync, mkdtempSync, mkdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

test('failed generator preserves every existing output', () => {
	const root = mkdtempSync(join(tmpdir(), 'carbon-proto-generation-'));
	const outputs = [
		'pkg/proto/example.go',
		'web/carbon-panel/src/lib/proto/example.ts',
		'web/carbon-panel/static/schemav1.yaml',
		'docs/carbon-panel/public/schemav1.yaml'
	];
	try {
		mkdirSync(join(root, 'scripts'));
		copyFileSync(
			join(dirname(fileURLToPath(import.meta.url)), 'proto-generate.mjs'),
			join(root, 'scripts/proto-generate.mjs')
		);
		for (const path of outputs) {
			mkdirSync(dirname(join(root, path)), { recursive: true });
			writeFileSync(join(root, path), `original ${path}\n`);
		}
		// Node itself is not Buf: it fails the attempted generator invocation.
		const version = spawnSync(process.execPath, ['--version'], { encoding: 'utf8' }).stdout.trim();
		const result = spawnSync(process.execPath, [join(root, 'scripts/proto-generate.mjs')], {
			env: { ...process.env, BUF: process.execPath, BUF_VERSION: version },
			encoding: 'utf8'
		});
		assert.notEqual(result.status, 0);
		assert.match(result.stderr, /failed with status/);
		for (const path of outputs)
			assert.equal(readFileSync(join(root, path), 'utf8'), `original ${path}\n`);
	} finally {
		rmSync(root, { recursive: true, force: true });
	}
});

test('replacement failure restores earlier outputs and preserves unexpected files', () => {
	const root = mkdtempSync(join(tmpdir(), 'carbon-proto-rollback-'));
	const original = {
		'pkg/proto/example.go': '// Code generated by fixture\nold go\n',
		'web/carbon-panel/src/lib/proto/user.txt': 'user file\n',
		'web/carbon-panel/static/schemav1.yaml': 'old schema\n',
		'docs/carbon-panel/public/schemav1.yaml': 'old docs schema\n'
	};
	try {
		mkdirSync(join(root, 'scripts'));
		copyFileSync(
			join(dirname(fileURLToPath(import.meta.url)), 'proto-generate.mjs'),
			join(root, 'scripts/proto-generate.mjs')
		);
		for (const [path, value] of Object.entries(original)) {
			mkdirSync(dirname(join(root, path)), { recursive: true });
			writeFileSync(join(root, path), value);
		}
		// A local Node script stands in for Buf and creates all staged products;
		// the formatter is also a harmless no-op. The second target then refuses
		// the non-generated user file after the first target was replaced.
		writeFileSync(
			join(root, 'generate'),
			`
const fs = require('node:fs'); const path = require('node:path');
const output = process.argv[process.argv.indexOf('-o') + 1];
for (const [name, value] of Object.entries({
  'pkg/proto/example.go': '// Code generated by fixture\\nnew go\\n',
  'web/carbon-panel/src/lib/proto/example.ts': '// @generated\\nnew ts\\n',
  'web/carbon-panel/static/schemav1.yaml': 'new schema\\n',
  'docs/carbon-panel/public/schemav1.yaml': 'new docs schema\\n'
})) { const dest = path.join(output, name); fs.mkdirSync(path.dirname(dest), {recursive:true}); fs.writeFileSync(dest, value); }
`
		);
		const prettier = join(root, 'web/carbon-panel/node_modules/prettier/bin/prettier.cjs');
		mkdirSync(dirname(prettier), { recursive: true });
		writeFileSync(prettier, 'process.exit(0);\n');
		const version = spawnSync('node', ['--version'], { encoding: 'utf8' }).stdout.trim();
		const result = spawnSync(process.execPath, [join(root, 'scripts/proto-generate.mjs')], {
			env: { ...process.env, BUF: 'node', BUF_VERSION: version, BUN: 'node' },
			encoding: 'utf8'
		});
		assert.notEqual(result.status, 0);
		assert.match(result.stderr, /Refusing to replace non-generated file/);
		for (const [path, value] of Object.entries(original))
			assert.equal(readFileSync(join(root, path), 'utf8'), value);
	} finally {
		rmSync(root, { recursive: true, force: true });
	}
});
